/** Child elements of a Lucide SVG as [tag, attributes] pairs. */
function nodes(svg) {
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
  return [...body.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v])),
  ])
}

const here = dirname(fileURLToPath(import.meta.url))

async function fetchSvg(lucide) {
  const res = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${lucide}.svg`)
  if (!res.ok) throw new Error(`${lucide}: HTTP ${res.status}`)
  return res.text()
}

/** Map with at most `limit` requests in flight. */
async function mapLimit(items, limit, fn) {
  const out = new Array(items.length)
  let next = 0
  await Promise.all(Array.from({ length: limit }, async () => {
    while (next < items.length) {
      const i = next++
      out[i] = await fn(items[i])
    }
  }))
  return out
}

const HEADER = `// Generated by scripts/gen-icons.mjs from lucide-static@${VERSION} (ISC license). Do not edit.`

const entries = await Promise.all(Object.entries(ICONS).map(async ([name, lucide]) =>
  `  ${JSON.stringify(name)}: ${JSON.stringify(nodes(await fetchSvg(lucide)))},`))

writeFileSync(join(here, '..', 'src', 'icons.ts'), `${HEADER}

export type IconNode = readonly (readonly [tag: string, attrs: Readonly<Record<string, string>>])[]

export const ICONS = {
${entries.join('\n')}
} as const satisfies Record<string, IconNode>

export type IconName = keyof typeof ICONS
`)
console.log(`wrote ${entries.length} icons`)

// Picker library: names missing from this Lucide version are skipped.
const groups = JSON.parse(readFileSync(join(here, 'icon-groups.json'), 'utf8'))
const names = [...new Set(groups.flatMap((g) => g.items))]
const svgs = await mapLimit(names, 24, (n) => fetchSvg(n).catch(() => null))
const library = new Map(names.flatMap((n, i) => (svgs[i] ? [[n, nodes(svgs[i])]] : [])))
const missing = names.filter((n) => !library.has(n))
if (missing.length) console.warn(`skipped ${missing.length} unknown icons: ${missing.join(', ')}`)
const keptGroups = groups
  .map((g) => ({ title: g.title, items: g.items.filter((n) => library.has(n)) }))
  .filter((g) => g.items.length)

writeFileSync(join(here, '..', 'src', 'icon-library.ts'), `${HEADER}
// Loaded on demand (icon picker, folder and tag icons); never import it statically.

import type { IconNode } from './icons'

export interface IconGroup { title: string; items: string[] }

export const ICON_GROUPS: IconGroup[] = ${JSON.stringify(keptGroups)}

export const ICON_LIBRARY: Record<string, IconNode> = {
${[...library].map(([n, v]) => `  ${JSON.stringify(n)}: ${JSON.stringify(v)},`).join('\n')}
}
`)
console.log(`wrote ${library.size} picker icons in ${keptGroups.length} groups`)
